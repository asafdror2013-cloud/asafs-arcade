#!/usr/bin/env python3
"""Turns Roblox's API-Dump.json into api.luau, the member table the emulator validates against.
usage: gen_api.py API-Dump.json api.luau"""
import json, sys

dump = json.load(open(sys.argv[1]))
BAD_SEC = {"RobloxScriptSecurity", "RobloxSecurity", "NotAccessibleSecurity", "LocalUserSecurity", "RobloxEngineSecurity"}

def sec_ok(m):
    s = m.get("Security")
    if isinstance(s, dict):
        return s.get("Read") not in BAD_SEC
    return s not in BAD_SEC

def vt(t):
    if not t:
        return "any"
    cat = t.get("Category")
    name = t.get("Name")
    return {"Enum": "e:", "Class": "c:", "DataType": "d:", "Primitive": "p:", "Group": "g:"}.get(cat, "?:") + name

def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

out = ["-- generated by gen_api.py from Roblox API-Dump.json " + str(dump.get("Version")), "return {", "classes = {"]
for c in dump["Classes"]:
    tags = set(c.get("Tags") or [])
    props, ro, funcs, events, depr = [], [], [], [], []
    for m in c["Members"]:
        if not sec_ok(m):
            continue
        mt = m["MemberType"]
        mtags = set(m.get("Tags") or [])
        if "NotScriptable" in mtags:
            continue
        n = m["Name"]
        if "Deprecated" in mtags:
            depr.append(n)
        if mt == "Property":
            props.append(f"[{q(n)}]={q(vt(m.get('ValueType')))}")
            if "ReadOnly" in mtags or (isinstance(m.get("Security"), dict) and m["Security"].get("Write") in BAD_SEC):
                ro.append(q(n))
        elif mt == "Function":
            funcs.append(q(n))
        elif mt == "Event":
            events.append(q(n))
    line = f"[{q(c['Name'])}]={{s={q(c.get('Superclass') or '')},nc={'true' if 'NotCreatable' in tags or 'Service' in tags else 'false'},svc={'true' if 'Service' in tags else 'false'},"
    line += "p={" + ",".join(props) + "},ro={" + ",".join(ro) + "},f={" + ",".join(funcs) + "},e={" + ",".join(events) + "},d={" + ",".join(q(x) for x in depr) + "}},"
    out.append(line)
out.append("},")
out.append("enums = {")
for e in dump["Enums"]:
    items = ",".join(f"{{{q(i['Name'])},{i['Value']}}}" for i in e["Items"])
    out.append(f"[{q(e['Name'])}]={{{items}}},")
out.append("},")
out.append("}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("wrote", sys.argv[2], len(dump["Classes"]), "classes", len(dump["Enums"]), "enums")
